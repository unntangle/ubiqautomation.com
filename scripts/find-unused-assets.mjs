/**
 * find-unused-assets.mjs
 * ---------------------------------------------------------------------------
 * Reports which files in public/ are never referenced anywhere in the source.
 *
 * WHY
 *
 *   This project was forked out of the parent unntangle.com app by
 *   scripts/migrate-from-parent.mjs, which copies public/images and
 *   public/uBIQ wholesale. Most of public/images belongs to the parent's
 *   marketing site and has no business shipping inside this one. Deleting
 *   those files saves more bandwidth than compressing them ever will, and
 *   stops the parent company's branding leaking into a client build.
 *
 * HOW IT DECIDES
 *
 *   Every file under public/ is matched by BASENAME against the full text of
 *   every source file under app/, components/, data/, lib/ and the root
 *   config files. Basename rather than full path, because references are
 *   written many different ways:
 *
 *       src="/images/hero.png"
 *       url('/uBIQ/uBIQ-logo.svg')          <- inside a .module.css
 *       `${SITE_URL}/uBIQ/uBIQ-logo.png`    <- inside a template literal
 *
 *   A basename match is deliberately generous. It will call a file "used"
 *   when the name merely appears in a comment, which is the safe direction to
 *   be wrong in: better to keep a dead file than delete a live one.
 *
 * WHAT IT CANNOT SEE
 *
 *   Paths assembled at runtime, e.g. `/images/${slug}.png`. Nothing that
 *   greps text can catch those. Skim the "unused" list before acting on it.
 *
 * USAGE
 *
 *   node scripts/find-unused-assets.mjs           # report only
 *   node scripts/find-unused-assets.mjs --trash   # move unused to public/_unused/
 *
 *   --trash MOVES rather than deletes, so it is reversible. Check the site
 *   still builds and looks right, then delete public/_unused/ by hand.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const TRASH = path.join(PUBLIC, "_unused");

/** Directories scanned for references. */
const SOURCE_DIRS = ["app", "components", "data", "lib", "src"];

/** Root-level files also scanned. */
const SOURCE_FILES = ["next.config.ts", "next.config.js", "next.config.mjs"];

/** Extensions treated as source text. */
const SOURCE_EXT = new Set([
    ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs",
    ".css", ".scss", ".sass", ".json", ".md", ".html",
]);

/** Never reported as unused even with no textual reference. */
const ALWAYS_KEEP = new Set([
    "favicon.ico",
    "robots.txt",
    "sitemap.xml",
    "manifest.webmanifest",
    "site.webmanifest",
    "browserconfig.xml",
    "apple-touch-icon.png",
    // Generated by scripts/optimize-images.mjs. Kept unconditionally so a scan
    // run before they are wired into layout.tsx / manifest.ts doesn't bin them.
    "fav-icon.png",
    "favicon-32.png",
    "apple-icon-180.png",
    "icon-192.png",
    "icon-512.png",
]);

const TRASH_MODE = process.argv.includes("--trash");

const toPosix = (p) => p.split(path.sep).join("/");
const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

// ---------------------------------------------------------------------------

function walk(dir, filter) {
    const out = [];
    if (!fs.existsSync(dir)) return out;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        if (entry.name === "node_modules" || entry.name === ".next") continue;
        if (entry.name === "_unused") continue;
        const abs = path.join(dir, entry.name);
        if (entry.isDirectory()) out.push(...walk(abs, filter));
        else if (!filter || filter(entry.name)) out.push(abs);
    }
    return out;
}

/** One big string of every source file, searched once per asset. */
function loadSourceText() {
    const files = [];

    for (const dir of SOURCE_DIRS) {
        files.push(
            ...walk(path.join(ROOT, dir), (name) =>
                SOURCE_EXT.has(path.extname(name).toLowerCase())
            )
        );
    }
    for (const name of SOURCE_FILES) {
        const abs = path.join(ROOT, name);
        if (fs.existsSync(abs)) files.push(abs);
    }

    const text = files
        .map((f) => {
            try {
                return fs.readFileSync(f, "utf8");
            } catch {
                return "";
            }
        })
        .join("\n");

    return { text, count: files.length };
}

// ---------------------------------------------------------------------------

function main() {
    if (!fs.existsSync(PUBLIC)) {
        console.error(`\n  No public/ directory at ${PUBLIC}\n`);
        process.exit(1);
    }

    const { text, count } = loadSourceText();
    const assets = walk(PUBLIC);

    // Stems (path without extension) of every asset that IS referenced. A
    // format sibling of a live file -- hero.webp next to a used hero.png --
    // must never be binned: scripts/optimize-images.mjs generates those on
    // purpose, and they are unreferenced only until the swap-over happens.
    const referencedStems = new Set();
    for (const abs of assets) {
        const base = path.basename(abs);
        if (text.includes(base)) {
            referencedStems.add(toPosix(path.relative(PUBLIC, abs)).replace(/\.[^.]+$/, ""));
        }
    }

    console.log(`\n  Unused asset scan`);
    console.log(`  scanned ${count} source files for ${assets.length} assets in public/\n`);

    const used = [];
    const unused = [];

    for (const abs of assets) {
        const rel = toPosix(path.relative(PUBLIC, abs));
        const base = path.basename(abs);
        const size = fs.statSync(abs).size;
        const relStem = rel.replace(/\.[^.]+$/, "");

        if (ALWAYS_KEEP.has(base)) {
            used.push({ rel, size, why: "reserved name" });
            continue;
        }

        if (text.includes(base)) {
            used.push({ rel, size, why: "referenced" });
            continue;
        }

        if (referencedStems.has(relStem)) {
            used.push({ rel, size, why: "sibling of referenced" });
            continue;
        }

        unused.push({ rel, size, abs });
    }

    const width = Math.max(...assets.map((a) => toPosix(path.relative(PUBLIC, a)).length), 24);

    console.log(`  USED  ${used.length}`);
    for (const u of used.sort((a, b) => a.rel.localeCompare(b.rel))) {
        console.log(`    ${u.rel.padEnd(width)}  ${kb(u.size).padStart(10)}  ${u.why}`);
    }

    const wasted = unused.reduce((sum, u) => sum + u.size, 0);

    console.log(`\n  UNUSED  ${unused.length}   (${kb(wasted)})`);
    if (unused.length === 0) {
        console.log(`    nothing to clean up.`);
    }
    for (const u of unused.sort((a, b) => b.size - a.size)) {
        console.log(`    ${u.rel.padEnd(width)}  ${kb(u.size).padStart(10)}`);
    }

    if (TRASH_MODE && unused.length > 0) {
        for (const u of unused) {
            const dest = path.join(TRASH, u.rel);
            fs.mkdirSync(path.dirname(dest), { recursive: true });
            fs.renameSync(u.abs, dest);
        }
        console.log(
            `\n  Moved ${unused.length} file(s) to public/_unused/.\n` +
            `  Run the site, confirm nothing is missing, then delete that folder.\n` +
            `  To undo, move them back.\n`
        );
    } else if (unused.length > 0) {
        console.log(
            `\n  Nothing was changed. Re-run with --trash to move these into\n` +
            `  public/_unused/ (reversible) instead of deleting them outright.\n\n` +
            `  Caution: paths built at runtime, e.g. \`/images/\${slug}.png\`, cannot\n` +
            `  be detected by a text scan. Skim the list above before acting.\n`
        );
    }
}

main();
